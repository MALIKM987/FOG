%% ------------------------------------------------------------
% PODSUMOWANIE MONTE CARLO
%% ------------------------------------------------------------

meanEst = zeros(Nlevels,1);
stdEst = zeros(Nlevels,1);
biasEst = zeros(Nlevels,1);
rmseEst = zeros(Nlevels,1);
snrRate = nan(Nlevels,1);

for ilvl = 1:Nlevels

    idxL = ...
        mcOmegaSet == omegaLevels(ilvl);

    vals = ...
        mcOmegaEst(idxL);

    errs = ...
        vals-omegaLevels(ilvl);

    meanEst(ilvl) = mean(vals);
    stdEst(ilvl) = std(vals);
    biasEst(ilvl) = mean(errs);
    rmseEst(ilvl) = sqrt(mean(errs.^2));

    if omegaLevels(ilvl) ~= 0 && stdEst(ilvl) > 0
        snrRate(ilvl) = ...
            abs(omegaLevels(ilvl))/stdEst(ilvl);
    end
end

zeroIdx = ...
    find(omegaLevels == 0,1);

sigmaZero = ...
    stdEst(zeroIdx);

biasZero = ...
    meanEst(zeroIdx);

threshold_1sigma = sigmaZero;
threshold_3sigma = 3*sigmaZero;

