% - dodaje napieciowy szum wzmacniacza jako rownowazny prad,
% - dodaje ograniczone pasmo TIA,
% - kompensuje faze i amplitude TIA w lock-in,
% - wykonuje Monte Carlo dla malych predkosci katowych.
%
