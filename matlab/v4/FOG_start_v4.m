%% ============================================================
% PARAMETRY FIZYCZNE FOG - JAK v3
%% ============================================================

c = 299792458;
lambda = 1550e-9;
L = 1000;
D = 0.160;
ng = 1.4682;

K_sag = 2*pi*L*D/(lambda*c);
tau = ng*L/c;
f_opt = 1/(2*tau);

%% ============================================================
% MODULATOR PZT
%% ============================================================

beta_target = 1.84;
f_mod = 20e3;

phi0 = beta_target / ...
    (2*abs(sin(pi*f_mod*tau)));

beta_eff = ...
    2*phi0*abs(sin(pi*f_mod*tau));

%% ============================================================
% OPTYCZNY BILANS MOCY - JAK v3
%% ============================================================

P_source_W = 1.0e-3;

K1_launch_ratio = 0.50;
K1_detector_ratio = 0.50;
IL_K1_dB = 0.20;

IL_connector_common_dB = 0.20;
IL_polarizer_dB = 0.80;
IL_depolarizer_dB = 0.30;

K2_split_ratio = 0.50;
IL_K2_dB = 0.20;

alpha_fiber_dB_km = 0.20;
IL_PZT_dB = 0.50;

N_loop_splices = 6;
IL_splice_dB = 0.05;

visibility = 1.0;

eta_K1 = 10^(-IL_K1_dB/10);
eta_conn = 10^(-IL_connector_common_dB/10);
eta_pol = 10^(-IL_polarizer_dB/10);
eta_dep = 10^(-IL_depolarizer_dB/10);

eta_K2 = 10^(-IL_K2_dB/10);

IL_coil_dB = ...
    alpha_fiber_dB_km*(L/1000);

eta_coil = 10^(-IL_coil_dB/10);
eta_PZT = 10^(-IL_PZT_dB/10);

IL_loop_splices_dB = ...
    N_loop_splices*IL_splice_dB;

eta_splices = ...
    10^(-IL_loop_splices_dB/10);

eta_loop = ...
    eta_coil*eta_PZT*eta_splices;

K_front_forward = ...
    K1_launch_ratio * eta_K1 * ...
    eta_conn * eta_pol * eta_dep;

K_sagnac_power = ...
    2*K2_split_ratio*(1-K2_split_ratio) * ...
    eta_K2^2 * eta_loop;

K_front_return = ...
    eta_dep * eta_pol * eta_conn * ...
    K1_detector_ratio * eta_K1;

Pdet_scale_W = ...
    P_source_W * ...
    K_front_forward * ...
    K_sagnac_power * ...
    K_front_return;

%% ============================================================
% PHOTORECEIVER v4 - NOMINALNE PARAMETRY
%% ============================================================

% Stale fizyczne
q_e = 1.602176634e-19;          % C
k_B = 1.380649e-23;             % J/K

% Fotodioda InGaAs - zalozenia v4
Rpd = 0.9;                      % A/W
I_dark_A = 5e-9;                % 5 nA

% TIA - zalozenia v4
Rf = 20e3;                      % Ohm
Rtia = Rf;                      % zgodnosc z v3

T_receiver_K = 300;             % K
f_tia_Hz = 200e3;               % pasmo -3 dB TIA
w_tia = 2*pi*f_tia_Hz;

% Nominalny low-noise amplifier
opamp_en_V_sqrtHz = 4e-9;       % V/sqrt(Hz)
opamp_in_A_sqrtHz = 2e-15;      % A/sqrt(Hz)

% Uproszczenie v4:
% en jest przeliczany na rownowazny prad en/Rf.
% Pelny noise-gain zależny od pojemnosci fotodiody dodamy pozniej.
opamp_en_eq_A_sqrtHz = ...
    opamp_en_V_sqrtHz/Rf;

%% ============================================================
% POLITYKA NUMERYCZNA v3.1
%% ============================================================

% FAST dla 20 kHz / Monte Carlo.
Ts_solver = 0.20e-6;
Ts_noise = Ts_solver;

% Dla dyskretnego bialego szumu:
% sigma_sample = ASD * sqrt(fs/2) = ASD/sqrt(2*Ts)
noise_sample_scale = ...
    1/sqrt(2*Ts_noise);

%% ============================================================
% SZUMY STALE FOTORECEIVERA
%% ============================================================

i_dark_shot_ASD = ...
    sqrt(2*q_e*I_dark_A);

i_johnson_ASD = ...
    sqrt(4*k_B*T_receiver_K/Rf);

i_opamp_current_ASD = ...
    opamp_in_A_sqrtHz;

i_opamp_voltage_eq_ASD = ...
    opamp_en_eq_A_sqrtHz;

sigma_dark_sample_A = ...
    i_dark_shot_ASD*noise_sample_scale;

sigma_johnson_sample_A = ...
    i_johnson_ASD*noise_sample_scale;

sigma_opamp_current_sample_A = ...
    i_opamp_current_ASD*noise_sample_scale;

sigma_opamp_voltage_sample_A = ...
    i_opamp_voltage_eq_ASD*noise_sample_scale;

%% ============================================================
% LOCK-IN + KOMPENSACJA TIA
%% ============================================================

fc_lp = 300;
lp_order = 4;
[b_lp,a_lp] = ...
    butter(lp_order,2*pi*fc_lp,'s');

J1beta = besselj(1,beta_eff);
K_ref = 1/beta_eff;

% Modul harmonicznej podstawowej po TIA.
Hmag_tia_fmod = ...
    1/sqrt(1+(f_mod/f_tia_Hz)^2);

% TIA powoduje opoznienie fazowe atan(f/fc).
tia_phase_lag_rad = ...
    atan(f_mod/f_tia_Hz);

% Referencje lock-in opozniamy o ten sam kat.
ref_delay_tia_s = ...
    tia_phase_lag_rad/(2*pi*f_mod);

% Normalizacja uwzglednia modul TIA przy f_mod.
K_norm = ...
    -1/( ...
    Pdet_scale_W * ...
    visibility * ...
    Rpd * ...
    Rf * ...
    Hmag_tia_fmod * ...
    J1beta);

K_phase_to_deg = ...
    (180/pi)/K_sag;

%% ============================================================
% SREDNIA MOC I ANALITYCZNY BUDZET SZUMOW
%% ============================================================

% Dla Omega = 0:
Pdet_avg_zero_W = ...
    Pdet_scale_W * ...
    (1 + visibility*besselj(0,beta_eff));

Iphoto_avg_A = ...
    Rpd*Pdet_avg_zero_W;

i_photo_shot_ASD = ...
    sqrt(2*q_e*Iphoto_avg_A);

i_total_ASD = sqrt( ...
    i_photo_shot_ASD^2 + ...
    i_dark_shot_ASD^2 + ...
    i_johnson_ASD^2 + ...
    i_opamp_current_ASD^2 + ...
    i_opamp_voltage_eq_ASD^2);

% Noise-equivalent bandwidth 1-rzedowego LPF TIA.
ENBW_tia_Hz = ...
    (pi/2)*f_tia_Hz;

Vn_photo_rms = ...
    i_photo_shot_ASD*Rf*sqrt(ENBW_tia_Hz);

Vn_dark_rms = ...
    i_dark_shot_ASD*Rf*sqrt(ENBW_tia_Hz);

Vn_johnson_rms = ...
    i_johnson_ASD*Rf*sqrt(ENBW_tia_Hz);

Vn_opamp_i_rms = ...
    i_opamp_current_ASD*Rf*sqrt(ENBW_tia_Hz);

Vn_opamp_en_rms = ...
    i_opamp_voltage_eq_ASD*Rf*sqrt(ENBW_tia_Hz);

Vn_total_rms = sqrt( ...
    Vn_photo_rms^2 + ...
    Vn_dark_rms^2 + ...
    Vn_johnson_rms^2 + ...
    Vn_opamp_i_rms^2 + ...
    Vn_opamp_en_rms^2);

noiseNames = [ ...
    "Photo shot"; ...
    "Dark-current shot"; ...
    "Rf Johnson"; ...
    "OpAmp current"; ...
    "OpAmp voltage equiv."; ...
    "TOTAL RSS" ...
    ];

asd_A_sqrtHz = [ ...
    i_photo_shot_ASD; ...
    i_dark_shot_ASD; ...
    i_johnson_ASD; ...
    i_opamp_current_ASD; ...
    i_opamp_voltage_eq_ASD; ...
    i_total_ASD ...
    ];

vrms_V = [ ...
    Vn_photo_rms; ...
    Vn_dark_rms; ...
    Vn_johnson_rms; ...
    Vn_opamp_i_rms; ...
    Vn_opamp_en_rms; ...
    Vn_total_rms ...
    ];

varianceShare = zeros(6,1);

varianceShare(1:5) = ...
    100*(vrms_V(1:5).^2)/(Vn_total_rms^2);

varianceShare(6) = 100;

noiseBudget = table( ...
    noiseNames, ...
    asd_A_sqrtHz*1e12, ...
    vrms_V*1e6, ...
    varianceShare, ...
    'VariableNames', ...
    { ...
    'Noise_source', ...
    'Input_ASD_pA_sqrtHz', ...
    'TIA_output_RMS_uV', ...
    'Variance_share_percent' ...
    });

writetable( ...
    noiseBudget, ...
    'FOG_v4_noise_budget.csv');

