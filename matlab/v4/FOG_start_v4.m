function buildPhotoreceiverV4(sub)

    Simulink.SubSystem.deleteContents(sub);

    %% Ports

    add_block( ...
        'simulink/Ports & Subsystems/In1', ...
        [sub '/P_detector'], ...
        'Port','1', ...
        'Position',[25 210 55 230]);

    add_block( ...
        'simulink/Ports & Subsystems/Out1', ...
        [sub '/V_TIA'], ...
        'Port','1', ...
        'Position',[1080 190 1110 210]);

    add_block( ...
        'simulink/Ports & Subsystems/Out1', ...
        [sub '/V_noise'], ...
        'Port','2', ...
        'Position',[1080 350 1110 370]);

    add_block( ...
        'simulink/Ports & Subsystems/Out1', ...
        [sub '/I_photo'], ...
        'Port','3', ...
        'Position',[1080 55 1110 75]);

    %% Photocurrent

    add_block( ...
        'simulink/Math Operations/Gain', ...
        [sub '/InGaAs Responsivity'], ...
        'Gain','Rpd', ...
        'Position',[100 195 220 245]);

    add_block( ...
        'simulink/Discontinuities/Saturation', ...
        [sub '/Positive Iphoto'], ...
        'UpperLimit','inf', ...
        'LowerLimit','0', ...
        'Position',[270 45 360 95]);

    %% Dark current DC

    add_block( ...
        'simulink/Sources/Constant', ...
        [sub '/Dark Current DC'], ...
        'Value','I_dark_A', ...
        'Position',[270 140 360 180]);

    add_block( ...
        'simulink/Math Operations/Sum', ...
        [sub '/Signal Current'], ...
        'Inputs','++', ...
        'Position',[440 180 480 250]);

    %% Photo shot noise - dynamic ASD = sqrt(2*q*Iphoto)

    add_block( ...
        'simulink/Math Operations/Gain', ...
        [sub '/2qI'], ...
        'Gain','2*q_e', ...
        'Position',[410 35 490 85]);

    add_block( ...
        'simulink/Math Operations/Math Function', ...
        [sub '/sqrt shot ASD'], ...
        'Operator','sqrt', ...
        'Position',[530 35 620 85]);

    add_block( ...
        'simulink/Math Operations/Gain', ...
        [sub '/ASD to sample sigma'], ...
        'Gain','noise_sample_scale', ...
        'Position',[660 35 780 85]);

    add_block( ...
        'simulink/Sources/Random Number', ...
        [sub '/Gaussian Photo'], ...
        'Mean','0', ...
        'Variance','1', ...
        'Seed','seed_photo', ...
        'SampleTime','Ts_noise', ...
        'Position',[660 105 780 145]);

    add_block( ...
        'simulink/Math Operations/Product', ...
        [sub '/Photo Shot Noise'], ...
        'Position',[830 55 880 115]);

    %% Constant noise sources

    addNoiseSource( ...
        sub,'Dark Shot Noise','Gaussian Dark', ...
        'sigma_dark_sample_A','seed_dark',[100 320]);

    addNoiseSource( ...
        sub,'Johnson Noise','Gaussian Johnson', ...
        'sigma_johnson_sample_A','seed_johnson',[100 400]);

    addNoiseSource( ...
        sub,'OpAmp Current Noise','Gaussian OpAmp I', ...
        'sigma_opamp_current_sample_A','seed_opamp_i',[100 480]);

    addNoiseSource( ...
        sub,'OpAmp Voltage Eq Noise','Gaussian OpAmp EN', ...
        'sigma_opamp_voltage_sample_A','seed_opamp_en',[100 560]);

    %% Noise sum

    add_block( ...
        'simulink/Math Operations/Sum', ...
        [sub '/Total Current Noise'], ...
        'Inputs','+++++', ...
        'Position',[910 320 950 510]);

    add_block( ...
        'simulink/Math Operations/Gain', ...
        [sub '/Noise Enable'], ...
        'Gain','noise_enable', ...
        'Position',[985 380 1060 430]);

    %% Total detector current

    add_block( ...
        'simulink/Math Operations/Sum', ...
        [sub '/Signal plus Noise'], ...
        'Inputs','++', ...
        'Position',[570 190 610 260]);

    %% TIA transfer functions

    add_block( ...
        'simulink/Continuous/Transfer Fcn', ...
        [sub '/TIA Signal and Noise'], ...
        'Numerator','Rf*w_tia', ...
        'Denominator','[1 w_tia]', ...
        'Position',[700 185 850 255]);

    add_block( ...
        'simulink/Continuous/Transfer Fcn', ...
        [sub '/TIA Noise Only'], ...
        'Numerator','Rf*w_tia', ...
        'Denominator','[1 w_tia]', ...
        'Position',[915 545 1040 605]);

    %% Connections signal path

    add_line( ...
        sub,'P_detector/1','InGaAs Responsivity/1', ...
        'autorouting','on');

    add_line( ...
        sub,'InGaAs Responsivity/1','Signal Current/1', ...
        'autorouting','on');

    add_line( ...
        sub,'Dark Current DC/1','Signal Current/2', ...
        'autorouting','on');

    add_line( ...
        sub,'Signal Current/1','Signal plus Noise/1', ...
        'autorouting','on');

    add_line( ...
        sub,'Noise Enable/1','Signal plus Noise/2', ...
        'autorouting','on');

    add_line( ...
        sub,'Signal plus Noise/1','TIA Signal and Noise/1', ...
        'autorouting','on');

    add_line( ...
        sub,'TIA Signal and Noise/1','V_TIA/1', ...
        'autorouting','on');

    %% Iphoto monitor

    add_line( ...
        sub,'InGaAs Responsivity/1','Positive Iphoto/1', ...
        'autorouting','on');

    add_line( ...
        sub,'Positive Iphoto/1','2qI/1', ...
        'autorouting','on');

    add_line( ...
        sub,'Positive Iphoto/1','I_photo/1', ...
        'autorouting','on');

    %% Photo shot

    add_line( ...
        sub,'2qI/1','sqrt shot ASD/1', ...
        'autorouting','on');

    add_line( ...
        sub,'sqrt shot ASD/1','ASD to sample sigma/1', ...
        'autorouting','on');

    add_line( ...
        sub,'ASD to sample sigma/1','Photo Shot Noise/1', ...
        'autorouting','on');

    add_line( ...
        sub,'Gaussian Photo/1','Photo Shot Noise/2', ...
        'autorouting','on');

    %% Noise components -> sum

    add_line( ...
        sub,'Photo Shot Noise/1','Total Current Noise/1', ...
        'autorouting','on');

    add_line( ...
        sub,'Dark Shot Noise/1','Total Current Noise/2', ...
        'autorouting','on');

    add_line( ...
        sub,'Johnson Noise/1','Total Current Noise/3', ...
        'autorouting','on');

    add_line( ...
        sub,'OpAmp Current Noise/1','Total Current Noise/4', ...
        'autorouting','on');

    add_line( ...
        sub,'OpAmp Voltage Eq Noise/1','Total Current Noise/5', ...
        'autorouting','on');

    add_line( ...
        sub,'Total Current Noise/1','Noise Enable/1', ...
        'autorouting','on');

    %% Noise-only monitor

    add_line( ...
        sub,'Noise Enable/1','TIA Noise Only/1', ...
        'autorouting','on');

    add_line( ...
        sub,'TIA Noise Only/1','V_noise/1', ...
        'autorouting','on');
end

function addNoiseSource(sub,outName,rngName,sigmaName,seedName,pos)

    x = pos(1);
    y = pos(2);

    add_block( ...
        'simulink/Sources/Random Number', ...
        [sub '/' rngName], ...
        'Mean','0', ...
        'Variance','1', ...
        'Seed',seedName, ...
        'SampleTime','Ts_noise', ...
        'Position',[x y x+120 y+40]);

    add_block( ...
        'simulink/Math Operations/Gain', ...
        [sub '/' outName], ...
        'Gain',sigmaName, ...
        'Position',[x+190 y-5 x+310 y+45]);

    add_line( ...
        sub, ...
        [rngName '/1'], ...
        [outName '/1'], ...
        'autorouting','on');
end

function insertTIAPhaseCompensation(sub)

    delayBlock = ...
        [sub '/TIA Phase Match'];

    if getSimulinkBlockHandle(delayBlock) ~= -1
        delete_block(delayBlock)
    end

    % Usun bezposrednie Reference -> Mixer.
    try
        delete_line( ...
            sub, ...
            'Reference/1', ...
            'LockIn Mixer/2')
    catch
        % Pozwala ponownie uruchomic skrypt na kopii modelu.
    end

    add_block( ...
        'simulink/Continuous/Transport Delay', ...
        delayBlock, ...
        'DelayTime','ref_delay_tia_s', ...
        'Position',[80 175 190 215]);

    add_line( ...
        sub, ...
        'Reference/1', ...
        'TIA Phase Match/1', ...
        'autorouting','on');

    add_line( ...
        sub, ...
        'TIA Phase Match/1', ...
        'LockIn Mixer/2', ...
        'autorouting','on');
end
