%% ============================================================
% PARAMETRY FIZYCZNE FOG
%% ============================================================

c = 299792458;
lambda = 1550e-9;
L = 1000;
D = 0.160;
ng = 1.4682;

K_sag = 2*pi*L*D/(lambda*c);
tau = ng*L/c;
f_opt = 1/(2*tau);

beta_target = 1.84;
f_mod = 20e3;

phi0 = ...
    beta_target/(2*abs(sin(pi*f_mod*tau)));

beta_eff = ...
    2*phi0*abs(sin(pi*f_mod*tau));

J1beta = besselj(1,beta_eff);
K_ref = 1/beta_eff;
K_phase_to_deg = (180/pi)/K_sag;

%% ============================================================
% OPTYKA / BUDZET MOCY - JAK v5
%% ============================================================

P_source_W = 1.0e-3;

K1_launch_ratio = 0.50;
K1_detector_ratio = 0.50;
IL_K1_dB = 0.20;

IL_connector_common_dB = 0.20;
IL_polarizer_dB = 0.80;
IL_depolarizer_dB = 0.30;

K2_split_ratio = 0.50;
IL_K2_dB = 0.20;

alpha_fiber_dB_km = 0.20;
IL_PZT_dB = 0.50;

N_loop_splices = 6;
IL_splice_dB = 0.05;

visibility = 1.0;

eta_K1 = 10^(-IL_K1_dB/10);
eta_conn = 10^(-IL_connector_common_dB/10);
eta_pol = 10^(-IL_polarizer_dB/10);
eta_dep = 10^(-IL_depolarizer_dB/10);
eta_K2 = 10^(-IL_K2_dB/10);

IL_coil_dB = alpha_fiber_dB_km*(L/1000);
eta_coil = 10^(-IL_coil_dB/10);
eta_PZT = 10^(-IL_PZT_dB/10);

IL_loop_splices_dB = ...
    N_loop_splices*IL_splice_dB;

eta_splices = ...
    10^(-IL_loop_splices_dB/10);

eta_loop = ...
    eta_coil*eta_PZT*eta_splices;

K_front_forward = ...
    K1_launch_ratio * eta_K1 * ...
    eta_conn * eta_pol * eta_dep;

K_sagnac_power = ...
    2*K2_split_ratio*(1-K2_split_ratio) * ...
    eta_K2^2 * eta_loop;

K_front_return = ...
    eta_dep * eta_pol * eta_conn * ...
    K1_detector_ratio * eta_K1;

Pdet_scale_W = ...
    P_source_W * ...
    K_front_forward * ...
    K_sagnac_power * ...
    K_front_return;

%% ============================================================
% PHOTORECEIVER - JAK v5
%% ============================================================

q_e = 1.602176634e-19;
k_B = 1.380649e-23;

Rpd = 0.9;
I_dark_A = 5e-9;

Rf = 20e3;
Rtia = Rf;

T_receiver_K = 300;

f_tia_Hz = 200e3;
w_tia = 2*pi*f_tia_Hz;

opamp_en_V_sqrtHz = 4e-9;
opamp_in_A_sqrtHz = 2e-15;
opamp_en_eq_A_sqrtHz = ...
    opamp_en_V_sqrtHz/Rf;

Pdet_avg_zero_W = ...
    Pdet_scale_W * ...
    (1 + besselj(0,beta_eff));

Iphoto_avg_A = ...
    Rpd*Pdet_avg_zero_W;

i_photo_shot_ASD = ...
    sqrt(2*q_e*Iphoto_avg_A);

i_dark_shot_ASD = ...
    sqrt(2*q_e*I_dark_A);

i_johnson_ASD = ...
    sqrt(4*k_B*T_receiver_K/Rf);

i_opamp_current_ASD = ...
    opamp_in_A_sqrtHz;

i_opamp_voltage_eq_ASD = ...
    opamp_en_eq_A_sqrtHz;

%% ============================================================
% ADC / DSP - WYNIK ROBOCZY v5.1
%% ============================================================

Vadc_min = 0.0;
Vadc_max = 2.0;
Vadc_fs = Vadc_max-Vadc_min;

adc_bits = 16;
fs_adc = 1e6;
Ts_adc = 1/fs_adc;
adc_sample_offset_s = 0;

% Po v5.1 przyjmujemy 100 kHz jako roboczy kandydat.
aa_order = 4;
f_aa_Hz = 100e3;

fc_digital_lp = 300;
digital_lp_order = 4;

q_adc = Vadc_fs/(2^adc_bits-1);

%% ============================================================
% MODEL POLARYZACJI v6
%% ============================================================

% Polaryzator:
% ER to nominalne zalozenie modelowe, jeszcze nie BOM.
polarizer_ER_dB = 25;
polarizer_leakage = 10^(-polarizer_ER_dB/10);

% Konserwatywna skala widzialnosci po polaryzatorze.
% DSP jest kalibrowany do tej wartosci.
V_cal = ...
    (1-polarizer_leakage)/(1+polarizer_leakage);

% Wlaczenie efektu polaryzacyjnego.
pol_enable = 1;

% depol_residual:
%   1.0 -> brak tlumienia wrazliwosci polaryzacyjnej,
%   0.0 -> idealne stlumienie efektu przez depolaryzator,
%   0.1 -> nominalny punkt badawczy v6.
%
% To parametr fenomenologiczny, NIE bezposrednio DOP z katalogu.
depol_residual = 0.10;

% Jones-equivalent disturbance:
% theta = wzgledne sprzezenie osi polaryzacji
% delta = wzgledna faza dwulamnosci
pol_theta0_rad = 15*pi/180;
pol_theta_amp_rad = 20*pi/180;

pol_delta0_rad = 0.20;
pol_delta_amp_rad = 0.30;

% Przyspieszone czestotliwosci zaburzen tylko do symulacji.
% Nie sa modelem widma termicznego prawdziwej cewki.
pol_theta_freq_Hz = 17;
pol_delta_freq_Hz = 23;
pol_delta_phase_rad = pi/5;

% Tylko mala czesc fazy overlap jest traktowana jako
% nieodwracalny polarization phase bias.
% Parametr musi zostac skalibrowany eksperymentalnie.
pol_nr_scale = 2.0e-4;

%% ============================================================
% KONFIGURACJA TIA + AAF + DIGITAL LPF
%% ============================================================

[b_aa,a_aa] = ...
    butter(aa_order,2*pi*f_aa_Hz,'s');

H_aa_fmod = ...
    polyval(b_aa,1j*2*pi*f_mod) / ...
    polyval(a_aa,1j*2*pi*f_mod);

H_tia_fmod = ...
    1/(1+1j*f_mod/f_tia_Hz);

H_analog_fmod = ...
    H_tia_fmod*H_aa_fmod;

Hmag_analog_fmod = ...
    abs(H_analog_fmod);

analog_phase_lag_rad = ...
    -angle(H_analog_fmod);

ref_delay_total_s = ...
    analog_phase_lag_rad/(2*pi*f_mod);

K_norm_digital = ...
    -1/( ...
    Pdet_scale_W * ...
    V_cal * ...
    Rpd * ...
    Rf * ...
    Hmag_analog_fmod * ...
    J1beta);

[b_dlp,a_dlp] = ...
    butter( ...
    digital_lp_order, ...
    fc_digital_lp/(fs_adc/2));

[sos_d,g_d] = tf2sos(b_dlp,a_dlp);
sos_d(1,1:3) = g_d*sos_d(1,1:3);

