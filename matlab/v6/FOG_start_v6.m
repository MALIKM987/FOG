    zeroMean(k) = mean(omega_ts.Data(idxO));
    zeroStd(k) = std(omega_ts.Data(idxO));

    Vmean(k) = mean(vpol_ts.Data(idxV));
    Vmin(k) = min(vpol_ts.Data(idxV));
    Vstd(k) = std(vpol_ts.Data(idxV));

    phiMean(k) = mean(phipol_ts.Data(idxP));
    phiStd(k) = std(phipol_ts.Data(idxP));
    phiMaxAbs(k) = max(abs(phipol_ts.Data(idxP)));

    % 1 deg/s - scale error
    Omega_deg_s = 1;
    out = sim(mdl);

    omega_ts = out.get('omega_est_ts');
    idxO = omega_ts.Time >= TmeanSweep;

    oneMean(k) = mean(omega_ts.Data(idxO));
    oneScaleErrorPct(k) = ...
        100*(oneMean(k)-1);

    fprintf( ...
        "r=%.2f: Vmin=%.5f, maxPhi=%.3e rad, zero=%+.3e, scaleErr=%+.4f %%\n", ...
        depol_residual,Vmin(k),phiMaxAbs(k), ...
        zeroMean(k),oneScaleErrorPct(k))
end

