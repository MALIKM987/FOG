function q = empiricalPercentile(x,p)

    x = sort(x(:));
    n = numel(x);

    if n == 0
        q = NaN;
        return
    end

    if n == 1
        q = x(1);
        return
    end

    pos = 1 + (n-1)*(p/100);
    i0 = floor(pos);
    i1 = ceil(pos);

    if i0 == i1
        q = x(i0);
    else
        w = pos-i0;
        q = (1-w)*x(i0) + w*x(i1);
    end
end
