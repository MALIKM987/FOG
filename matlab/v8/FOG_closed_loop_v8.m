% FOG - PARAMETRY ZWERYFIKOWANE
%% ============================================================

c = 299792458;
lambda = 1550e-9;

L = 1000;
D = 159.394500392266e-3;
ng = 1.4682;

K_sag = ...
    2*pi*L*D/(lambda*c);

tau = ...
    ng*L/c;

K_phase_to_deg_s = ...
    (180/pi)/K_sag;

% Wymagana szybkosc rampy fazy:
% Delta_phi_fb = slope * tau
% K_sag * Omega_rad_s + Delta_phi_fb = 0
slope_per_deg_s = ...
    K_sag*(pi/180)/tau;

wrap2pi_per_deg_s_Hz = ...
    slope_per_deg_s/(2*pi);

Omega_range_deg_s = 20;

slope_fullscale_rad_s = ...
    slope_per_deg_s*Omega_range_deg_s;

wrap2pi_fullscale_Hz = ...
    wrap2pi_per_deg_s_Hz*Omega_range_deg_s;

fprintf("K_sag                   = %.9f rad/(rad/s)\n",K_sag)
fprintf("tau                     = %.6f us\n",tau*1e6)
fprintf("phase slope / deg/s     = %.3f rad/s\n",slope_per_deg_s)
fprintf("2pi wraps / deg/s       = %.3f Hz\n",wrap2pi_per_deg_s_Hz)
fprintf("2pi wrap @20 deg/s      = %.3f kHz\n",wrap2pi_fullscale_Hz/1e3)

