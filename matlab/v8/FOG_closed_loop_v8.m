    NaN; ...
    0.18e-6; ...
    NaN ...
    ];

Na = numel(actuator);

availableCyclesByVoltage = zeros(Na,1);
availableCyclesBySpec = zeros(Na,1);
usableCycles = zeros(Na,1);

resetAtFull_Hz = zeros(Na,1);
requiredBW_Hz = zeros(Na,1);
maxOmegaByReset_deg_s = zeros(Na,1);
VppUsed_V = zeros(Na,1);
rampCurrent_A = NaN(Na,1);
resetPeakCurrent_A = NaN(Na,1);
feasible20deg = false(Na,1);

for k = 1:Na

    availableCyclesByVoltage(k) = ...
        floor(driverVpp_V(k)/(2*Vpi_design_V(k)));

    if isinf(phaseRangeSpec_pi(k))
        availableCyclesBySpec(k) = Inf;
    else
        availableCyclesBySpec(k) = ...
            floor(phaseRangeSpec_pi(k)/2);
    end

    usableCycles(k) = ...
        min(availableCyclesByVoltage(k),availableCyclesBySpec(k));

    if usableCycles(k) < 1
        usableCycles(k) = 0;
        continue
    end

    resetAtFull_Hz(k) = ...
        wrap2pi_fullscale_Hz/usableCycles(k);

    requiredBW_Hz(k) = ...
        0.35*resetAtFull_Hz(k)/reset_fraction;

    maxResetFreq = ...
        reset_fraction*actuatorBW_Hz(k)/0.35;

    maxOmegaByReset_deg_s(k) = ...
        maxResetFreq*usableCycles(k)/wrap2pi_per_deg_s_Hz;

    VppUsed_V(k) = ...
        2*Vpi_design_V(k)*usableCycles(k);

    if ~isnan(piezoCap_F(k))

        rampCurrent_A(k) = ...
            piezoCap_F(k)* ...
            VppUsed_V(k)* ...
            resetAtFull_Hz(k);

        resetPeakCurrent_A(k) = ...
            rampCurrent_A(k)/reset_fraction;
    end

    feasible20deg(k) = ...
        actuatorBW_Hz(k) >= requiredBW_Hz(k) && ...
        maxOmegaByReset_deg_s(k) >= Omega_range_deg_s;
end

