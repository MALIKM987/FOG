                0.35*fReset/reset_fraction;

            maxFreset = ...
                reset_fraction*20e3/0.35;

            omegaMax = ...
                maxFreset*Ncycles/wrap2pi_per_deg_s_Hz;

            cReset_kHz(row) = fReset/1e3;
            cBWreq_kHz(row) = bwReq/1e3;
            cOmegaMax(row) = omegaMax;
            cPass20(row) = omegaMax>=20;
        end
    end
end

