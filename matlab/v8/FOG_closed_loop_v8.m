% - wyznaczyc wymagania NCO/DAC,
% - wygenerowac BOM closed-loop i model FOG_v8.slx.
%
% WAZNE:
% v8 rozdziela dwa problemy:
%
% 1) BASEBAND LOOP:
%    residual Omega -> PI -> commanded feedback Omega.
%
% 2) PHYSICAL PHASE-RAMP ACTUATOR:
%    feedback Omega -> phase slope -> finite phase range -> reset.
%
% Model reset-bandwidth jest wymaganiem inzynierskim:
% przyjmujemy tr_10-90 ~= 0.35/BW i wymagamy,
% aby reset zajmowal <= reset_fraction okresu sawtooth.
%
% To nie jest pelny model rezonansow konkretnego PZT.
% Konkretna sztuka musi przejsc test rampy / resetu.
