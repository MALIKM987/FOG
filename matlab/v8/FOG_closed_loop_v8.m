% FUNKCJE
%% ============================================================

function [settling_s,overshoot_pct,residualRMS,estimateRMS,saturated] = ...
    simulateClosedLoop( ...
    rate_deg_s,fs,bwMeas,bwAct,Kp,Ki,limit,noiseSTD,seed)

    rng(seed);

    dt = 1/fs;
    T = 0.5;

    N = round(T*fs);

    stepIdx = round(0.05*fs)+1;

    omegaTrue = zeros(N,1);
    omegaTrue(stepIdx:end) = rate_deg_s;

    alphaMeas = ...
        1-exp(-2*pi*bwMeas*dt);

    alphaAct = ...
        1-exp(-2*pi*bwAct*dt);

    meas = 0;
    integ = 0;
    feedback = 0;

    feedbackLog = zeros(N,1);
    residualLog = zeros(N,1);
    estimateError = zeros(N,1);

    saturated = false;

    for k = 1:N

        residual = ...
            omegaTrue(k)-feedback;

        measurement = ...
            residual+noiseSTD*randn();

        meas = ...
            meas+alphaMeas*(measurement-meas);

        integCandidate = ...
            integ+Ki*meas*dt;

        uUnsat = ...
            Kp*meas+integCandidate;

        u = ...
            min(max(uUnsat,-limit),limit);

        if abs(u-uUnsat)>1e-12
            saturated = true;
        end

        % Simple conditional anti-windup.
        if abs(u-uUnsat)<1e-12 || ...
           (u>=limit && meas<0) || ...
           (u<=-limit && meas>0)

            integ = integCandidate;
        end

        feedback = ...
            feedback+alphaAct*(u-feedback);

        feedbackLog(k) = feedback;
        residualLog(k) = residual;
        estimateError(k) = feedback-omegaTrue(k);
    end

    t = (0:N-1)'*dt;

    tol = max(0.02*abs(rate_deg_s),1e-6);

    settling_s = NaN;

    for k = stepIdx:N

        if all(abs(estimateError(k:end))<=tol)
            settling_s = t(k)-t(stepIdx);
            break
        end
    end

    postStep = stepIdx:N;

    if rate_deg_s ~= 0
        overshoot_pct = ...
            100*(max(feedbackLog(postStep))-rate_deg_s)/abs(rate_deg_s);
    else
        overshoot_pct = 0;
    end

    steady = ...
        t>=0.30;

    residualRMS = ...
        sqrt(mean(residualLog(steady).^2));

    estimateRMS = ...
        sqrt(mean(estimateError(steady).^2));
end
