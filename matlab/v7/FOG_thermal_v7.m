% Geometria warstw z v6.3.
layerLength_m = [ ...
    54.1354910668731; ...
    54.3042699905946; ...
    54.4730489143160; ...
    54.6418278380375; ...
    54.8106067617590; ...
    54.9793856854804; ...
    55.1481646092019; ...
    55.3169435329233; ...
    55.4857224566448; ...
