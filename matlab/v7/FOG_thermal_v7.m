%% ============================================================
% PARAMETRY ZABLOKOWANE Z v6.3
%% ============================================================

c = 299792458;
lambda = 1550e-9;

L0 = 1000;
D0 = 159.394500392266e-3;

ng0 = 1.4682;

K_sag0 = ...
    2*pi*L0*D0/(lambda*c);

f_mod = 20e3;
beta_target = 1.84;

tau0 = ng0*L0/c;

phi0 = ...
    beta_target/(2*abs(sin(pi*f_mod*tau0)));

J1beta0 = besselj(1,beta_target);

Tref_C = 25;

% Cel detekcji projektu:
target_rate_deg_s = 1e-4;
target_rate_deg_h = target_rate_deg_s*3600;

% Alokujemy 1/3 docelowego sygnalu na thermal error.
thermal_budget_deg_h = ...
    target_rate_deg_h/3;

% Maksymalna predkosc do testu scale-factor.
Omega_fullscale_test_deg_s = 20;

%% ============================================================
% WLASCIWOSCI WLOKNA KRZEMIONKOWEGO
%% ============================================================

% Efektywny indeks do Shupe.
n_eff = 1.4445;

% Benchmark room-temperature 1550 nm.
dn_dT = 8.4e-6;                 % 1/K
alpha_fiber = 0.55e-6;          % 1/K

% Do tau(T) stosujemy ten sam rzad thermo-optic.
dng_dT = dn_dT;

%% ============================================================
% MATERIALY FORMERA - BENCHMARKI
%
% Nie sa to jeszcze konkretne partie materialu zakupowego.
% Po wyborze klasy wymagamy datasheet konkretnej plyty/pretow.
%% ============================================================

material = [ ...
    "Al6061-T6"; ...
    "Invar36"; ...
    "G10-FR4"; ...
    "POM-C"; ...
    "FusedSilica benchmark" ...
    ];

CTE_1_K = [ ...
    23.6e-6; ...
    1.30e-6; ...
    9.0e-6; ...
    110e-6; ...
    0.55e-6 ...
    ];

k_W_mK = [ ...
    167; ...
    10.5; ...
    0.30; ...
    0.31; ...
    1.38 ...
    ];

rho_kg_m3 = [ ...
    2700; ...
    8055; ...
    1820; ...
    1410; ...
    2203 ...
    ];

cp_J_kgK = [ ...
    896; ...
    515; ...
    1000; ...
    1500; ...
    703 ...
    ];

material_note = [ ...
    "very high conductivity; high CTE mismatch to silica"; ...
    "low CTE; moderate conductivity; precision-instrument class"; ...
    "moderate CTE; low through-thickness conductivity"; ...
    "easy machining but very high CTE"; ...
    "reference only; not default mechanical spool" ...
    ];

Nm = numel(material);

thermal_diffusivity_m2_s = ...
    k_W_mK./(rho_kg_m3.*cp_J_kgK);

CTE_mismatch_ppm_K = ...
    abs(CTE_1_K-alpha_fiber)*1e6;

%% ============================================================
% v7A - JEDNORODNA TEMPERATURA / SCALE FACTOR
%% ============================================================

disp("")
disp("==============================================")
disp(" v7A - UNIFORM TEMPERATURE SCALE FACTOR")
disp("==============================================")

T_sweep_C = (-10:5:60)';
Nt = numel(T_sweep_C);

rows = Nm*Nt;

matCol = strings(rows,1);
tempCol = zeros(rows,1);
diameter_mm = zeros(rows,1);
length_m = zeros(rows,1);
ngCol = zeros(rows,1);
betaCol = zeros(rows,1);
scaleFactor = zeros(rows,1);
scaleError_ppm = zeros(rows,1);
errorAt1_deg_s = zeros(rows,1);
errorAt20_deg_s = zeros(rows,1);

uniformCoeff_ppm_K = zeros(Nm,1);
allowedSensorError_C = zeros(Nm,1);

row = 0;

for km = 1:Nm

    alphaFormer = CTE_1_K(km);

    for kt = 1:Nt

        row = row+1;

        dT = T_sweep_C(kt)-Tref_C;

        Lt = ...
            L0*(1+alpha_fiber*dT);

        Dt = ...
            D0*(1+alphaFormer*dT);

        ngt = ...
            ng0+dng_dT*dT;

        taut = ...
            ngt*Lt/c;

        betat = ...
            2*phi0*abs(sin(pi*f_mod*taut));

        Kt = ...
            2*pi*Lt*Dt/(lambda*c);

        modulationGainRatio = ...
            besselj(1,betat)/J1beta0;

        sf = ...
            (Kt/K_sag0)*modulationGainRatio;

        matCol(row) = material(km);
        tempCol(row) = T_sweep_C(kt);
        diameter_mm(row) = Dt*1e3;
        length_m(row) = Lt;
        ngCol(row) = ngt;
        betaCol(row) = betat;
        scaleFactor(row) = sf;
        scaleError_ppm(row) = (sf-1)*1e6;
        errorAt1_deg_s(row) = (sf-1)*1;
        errorAt20_deg_s(row) = ...
            (sf-1)*Omega_fullscale_test_deg_s;
    end

    % Lokalny wspolczynnik w 25 C.
    epsT = 0.01;

    sfPlus = thermalScaleFactor( ...
        Tref_C+epsT,Tref_C, ...
        L0,D0,ng0,dng_dT,alpha_fiber,alphaFormer, ...
        c,lambda,f_mod,phi0,K_sag0,J1beta0);

    sfMinus = thermalScaleFactor( ...
        Tref_C-epsT,Tref_C, ...
        L0,D0,ng0,dng_dT,alpha_fiber,alphaFormer, ...
        c,lambda,f_mod,phi0,K_sag0,J1beta0);

    coeff = ...
        (sfPlus-sfMinus)/(2*epsT);

    uniformCoeff_ppm_K(km) = ...
        coeff*1e6;

    allowedSensorError_C(km) = ...
        target_rate_deg_s / ...
        (Omega_fullscale_test_deg_s*abs(coeff));
end

