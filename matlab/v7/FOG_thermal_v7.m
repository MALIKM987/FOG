function sf = thermalScaleFactor( ...
    T,Tref,L0,D0,ng0,dngdT,alphaFiber,alphaFormer, ...
    c,lambda,fmod,phi0,K0,J1beta0)

    dT = T-Tref;

    Lt = ...
        L0*(1+alphaFiber*dT);

    Dt = ...
        D0*(1+alphaFormer*dT);

    ngt = ...
        ng0+dngdT*dT;

    taut = ...
        ngt*Lt/c;

    beta = ...
        2*phi0*abs(sin(pi*fmod*taut));

    Kt = ...
        2*pi*Lt*Dt/(lambda*c);

    sf = ...
        (Kt/K0)*besselj(1,beta)/J1beta0;
end

function [t,Tlayers,dTdtLayers] = ...
    simulateRadialThermalModel( ...
    Nlayers,T0,stepC,rampCmin,tauOuter,tauInner,dt,Tend)

    t = (0:dt:Tend);

    ramp_C_s = ...
        rampCmin/60;

    Tamb = ...
        T0 + min(ramp_C_s*t,stepC);

    depth = ...
        linspace(0,1,Nlayers)';

    tauLayer = ...
        tauOuter + ...
        depth*(tauInner-tauOuter);

    Tlayers = ...
        T0*ones(Nlayers,numel(t));

    for k = 2:numel(t)

        for il = 1:Nlayers

            Tlayers(il,k) = ...
                Tlayers(il,k-1) + ...
                dt*(Tamb(k-1)-Tlayers(il,k-1))/tauLayer(il);
        end
    end

    dTdtLayers = zeros(size(Tlayers));

    for il = 1:Nlayers
        dTdtLayers(il,:) = ...
            gradient(Tlayers(il,:),dt);
    end
end

function [rmsErr,p95Err,maxErr] = ...
    evaluateTwoSensorCompensation( ...
    t,Tlayers,omegaTrueDegH,weights,shupeCoeff,qadFraction, ...
    samplePeriod,noiseSTD,filterTau,seed)

    rng(seed);

    dt = t(2)-t(1);

    sampleStep = ...
        max(1,round(samplePeriod/dt));

    idx = ...
        1:sampleStep:numel(t);

    ts = t(idx);

    Touter = ...
        Tlayers(1,idx);

    Tinner = ...
        Tlayers(end,idx);

    Touter = ...
        Touter + noiseSTD*randn(size(Touter));

    Tinner = ...
        Tinner + noiseSTD*randn(size(Tinner));

    alphaLP = ...
        samplePeriod/(filterTau+samplePeriod);

    TouterF = Touter;
    TinnerF = Tinner;

    for k = 2:numel(ts)

        TouterF(k) = ...
            TouterF(k-1) + ...
            alphaLP*(Touter(k)-TouterF(k-1));

        TinnerF(k) = ...
            TinnerF(k-1) + ...
            alphaLP*(Tinner(k)-TinnerF(k-1));
    end

    dOuter = ...
        gradient(TouterF,samplePeriod);

    dInner = ...
        gradient(TinnerF,samplePeriod);

    Nlayers = size(Tlayers,1);

    depth = ...
        linspace(0,1,Nlayers)';

    dLayerEst = zeros(Nlayers,numel(ts));

    for il = 1:Nlayers

        dLayerEst(il,:) = ...
            (1-depth(il))*dOuter + ...
            depth(il)*dInner;
    end

    integralEst = ...
        weights.'*dLayerEst;

    omegaEstDegH = ...
        qadFraction * ...
        shupeCoeff*integralEst * ...
        180/pi*3600;

    omegaTrueSampled = ...
        interp1(t,omegaTrueDegH,ts,'linear');

    residual = ...
        omegaTrueSampled-omegaEstDegH;

    % Pomijamy start filtru.
    valid = ...
        ts >= max(30,3*filterTau);

    r = residual(valid);

    rmsErr = ...
        sqrt(mean(r.^2));

    p95Err = ...
        empiricalPercentile(abs(r),95);

    maxErr = ...
        max(abs(r));
end

function q = empiricalPercentile(x,p)

    x = sort(x(:));
    n = numel(x);

    if n == 0
        q = NaN;
        return
    end

    if n == 1
        q = x(1);
        return
    end

    pos = 1 + (n-1)*(p/100);

    i0 = floor(pos);
    i1 = ceil(pos);

    if i0 == i1
        q = x(i0);
    else
        w = pos-i0;
        q = (1-w)*x(i0)+w*x(i1);
    end
end
