    55.8232803040877; ...
    55.9920592278092; ...
    56.1608381515306; ...
    56.3296170752521; ...
    56.4983959989735; ...
    56.6671749226950; ...
    56.8359538464164; ...
    56.7427182370387 ...
    ];

Nlayers = numel(layerLength_m);

layerEdges_m = ...
    [0;cumsum(layerLength_m)];

% Dokladna calka (L-2l) dl po danym zakresie wlokna.
shupeWeight_m2 = zeros(Nlayers,1);

for kl = 1:Nlayers

    a = layerEdges_m(kl);
    b = layerEdges_m(kl+1);

    shupeWeight_m2(kl) = ...
        L0*(b-a) - (b^2-a^2);
end

shupeCoeff = ...
    n_eff/(D0*L0) * ...
    (dn_dT+n_eff*alpha_fiber);

% Model niedoskonalosci uzwojenia symetrycznego.
winding_asymmetry_fraction = 0.02;

former_wall_m = 5e-3;

% tau_outer reprezentuje thermal enclosure / insulation,
% a nie stala materialowa.
tauOuterSweep_s = [15 30 60 120]';
rampSweep_C_min = [1 5]';

thermal_step_C = 10;

dtThermal_s = 0.1;
Tend_s = 900;

Nramp = numel(rampSweep_C_min);
Ntau = numel(tauOuterSweep_s);

NrowsThermal = Nm*Nramp*Ntau;

thMaterial = strings(NrowsThermal,1);
thRamp = zeros(NrowsThermal,1);
thTauOuter = zeros(NrowsThermal,1);
thTauInner = zeros(NrowsThermal,1);
thMaxSeq_deg_h = zeros(NrowsThermal,1);
thMaxQAD_deg_h = zeros(NrowsThermal,1);
thRMSQAD_deg_h = zeros(NrowsThermal,1);
thRequiredAsymPct = zeros(NrowsThermal,1);
thPassBudget = false(NrowsThermal,1);

row = 0;

for km = 1:Nm

    diffusivity = thermal_diffusivity_m2_s(km);

    conductionDelay_s = ...
        former_wall_m^2/diffusivity;

    for kr = 1:Nramp

        ramp_C_min = rampSweep_C_min(kr);

        for ktau = 1:Ntau

            row = row+1;

            tauOuter_s = ...
                tauOuterSweep_s(ktau);

            tauInner_s = ...
                tauOuter_s+conductionDelay_s;

            [t,Tlayers,dTdtLayers] = ...
                simulateRadialThermalModel( ...
                Nlayers,Tref_C,thermal_step_C, ...
                ramp_C_min,tauOuter_s,tauInner_s, ...
                dtThermal_s,Tend_s);

            shupeIntegral = ...
                shupeWeight_m2.'*dTdtLayers;

            omegaSeq_rad_s = ...
                shupeCoeff*shupeIntegral;

            omegaQAD_rad_s = ...
                winding_asymmetry_fraction*omegaSeq_rad_s;

            omegaSeq_deg_h = ...
                omegaSeq_rad_s*180/pi*3600;

            omegaQAD_deg_h = ...
                omegaQAD_rad_s*180/pi*3600;

            maxSeq = ...
                max(abs(omegaSeq_deg_h));

            maxQAD = ...
                max(abs(omegaQAD_deg_h));

            rmsQAD = ...
                sqrt(mean(omegaQAD_deg_h.^2));

            if maxSeq > 0
                requiredAsym = ...
                    100*thermal_budget_deg_h/maxSeq;
            else
                requiredAsym = Inf;
            end

            thMaterial(row) = material(km);
            thRamp(row) = ramp_C_min;
            thTauOuter(row) = tauOuter_s;
            thTauInner(row) = tauInner_s;
            thMaxSeq_deg_h(row) = maxSeq;
            thMaxQAD_deg_h(row) = maxQAD;
            thRMSQAD_deg_h(row) = rmsQAD;
            thRequiredAsymPct(row) = requiredAsym;
            thPassBudget(row) = ...
                maxQAD <= thermal_budget_deg_h;
        end
    end
end

thermalTransientResults = table( ...
