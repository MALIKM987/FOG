% Interferometryczny zyroskop swiatlowodowy - model v7
% MATLAB / Simulink R2023b
%
% CEL:
% - zbadac temperaturowy dryft scale factor,
% - dodac czysty efekt Shupe dla niejednorodnego pola temperatury,
% - porownac materialy formy cewki pod BOM,
% - wyznaczyc wymaganie na izolacje termiczna,
% - wyznaczyc wymagania na czujniki temperatury i ich odczyt,
% - zbudowac thermal BOM / acceptance plan.
%
% v7 jest modelem projektowym i wrazliwosciowym.
% NIE modeluje jeszcze pelnego termo-mechanicznego stresu coatingu,
% kleju i pottingu. Roznice CTE sa traktowane jako jawny stress-risk
% proxy, a nie jako pelny model fotoelastyczny.
%
% Efekt Shupe:
% Omega_E(t) = n/(D L) * (dn/dT + n*alpha_fiber)
%              * integral[ dT/dt(l,t) * (L-2l) dl ]
%
% Dla uzwojenia symetrycznego uzywamy jawnego parametru
% winding_asymmetry_fraction. Nie oznacza on gwarantowanej redukcji
% konkretnego realnego QAD, tylko model niedoskonalosci symetrii.
%% ============================================================

