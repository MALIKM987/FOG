%% ============================================================
% FOG_stress_v7_1.m
% Interferometryczny zyroskop swiatlowodowy - model v7.1
% MATLAB R2023b
%
% CEL:
% - rozdzielic pure Shupe od stress-induced T-dot / Mohr effect,
% - sprawdzic, czy provisional Invar36 nadal ma sens,
% - wyznaczyc dopuszczalny transfer odksztalcen termicznych,
% - wyznaczyc wymaganie na symetrie par uzwojenia,
% - zablokowac proces nawijania i tension-control,
% - okreslic, czego NIE wolno jeszcze zamykac w pottingu bez pomiaru,
% - wygenerowac thermo-mechanical BOM + acceptance plan.
%
% MODEL:
% Korzystamy z rozdzielenia:
%
% Omega_E = pure Shupe term + Mohr/T-dot term
%
% Dla jednorodnego T-dot i stalej roznicy wspolczynnika
% termo-optyczno-odksztalceniowego miedzy para symetryczna:
%
% Omega_M = ng*L/(4D) * Delta(n*S) * Tdot
%
% gdzie w tym modelu wrazliwosciowym:
%
% Delta(n*S) =
% n_eff*(1-p_e) * pair_mismatch * strain_transfer
% * (alpha_structure-alpha_fiber)
%
% strain_transfer = 0 ... 1 jest EFEKTYWNYM parametrem transferu
% odksztalcen. Nie jest on bezposrednio Young modulus ani nazwa kleju.
%
% v7.1 nie zastepuje FEM ani pomiaru Rayleigh-OFDR.
% Ma podac wymagania procesowe i zakres bezpiecznej konstrukcji.
%% ============================================================

clc
close all

