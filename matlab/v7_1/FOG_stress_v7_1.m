function omega_deg_h = mohrRateDegH( ...
    ng,ne,pe,L,D,alphaStructure,alphaFiber,eta,mismatch,rampCmin)

    deltaAlpha = ...
        mismatch*eta*(alphaStructure-alphaFiber);

    deltaNS = ...
        ne*(1-pe)*deltaAlpha;

    Tdot = ...
        rampCmin/60;

    omega_rad_s = ...
        ng*L/(4*D)*deltaNS*Tdot;

    omega_deg_h = ...
        omega_rad_s*180/pi*3600;
end

function maxMismatch = maxAllowedCTEMismatch( ...
    ng,ne,pe,L,D,eta,mismatch,rampCmin,budgetDegH)

    budgetRadS = ...
        budgetDegH/3600*pi/180;

    Tdot = rampCmin/60;

    denom = ...
        ng*L/(4*D)*ne*(1-pe)*eta*mismatch*Tdot;

    if denom == 0
        maxMismatch = Inf;
    else
        maxMismatch = budgetRadS/abs(denom);
    end
end
