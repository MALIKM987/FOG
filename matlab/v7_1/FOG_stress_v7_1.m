disp(" FOG v7.1 - THERMO-MECHANICAL STRESS / T-DOT")
disp("==============================================")

%% ============================================================
% PARAMETRY FOG / BUDZETY
%% ============================================================

L = 1000;
D = 159.394500392266e-3;

n_eff = 1.4445;
n_g = 1.4682;

alpha_fiber = 0.55e-6;

% Efektywny strain-optic coefficient silica.
% Benchmark engineering value.
p_e = 0.22;

target_rate_deg_s = 1e-4;
target_rate_deg_h = target_rate_deg_s*3600;

thermal_budget_deg_h = target_rate_deg_h/3;     % 0.12 deg/h

% Po v7 okolo polowy thermal budget zostawiamy na
% residual pure-Shupe / sensor compensation, a polowe na stress T-dot.
stress_budget_deg_h = thermal_budget_deg_h/2;   % 0.06 deg/h

ramp_design_C_min = 5;
Tdot_design_C_s = ramp_design_C_min/60;

% Acceptance slope dla liniowego stress T-dot modelu.
K_Tdot_max_deg_h_per_C_min = ...
    stress_budget_deg_h/ramp_design_C_min;

%% ============================================================
% MATERIALY FORMERA - JAK v7
%% ============================================================

