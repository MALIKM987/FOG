    0.02; ...
    0.05; ...
    0.10; ...
    0.30; ...
    0.70 ...
    ];

pairMismatchSweep = [ ...
    0.005; ...
    0.010; ...
    0.020; ...
    0.050 ...
    ];

rampSweep_C_min = [1;5];

%% ============================================================
% v7.1A - STRESS T-DOT SWEEP
%% ============================================================

disp("")
disp("==============================================")
disp(" v7.1A - MOHR / T-DOT STRESS SWEEP")
disp("==============================================")

Nrows = ...
    Nm*numel(strainTransfer)* ...
    numel(pairMismatchSweep)* ...
    numel(rampSweep_C_min);

outMaterial = strings(Nrows,1);
outTransferName = strings(Nrows,1);
outEta = zeros(Nrows,1);
outMismatch = zeros(Nrows,1);
outRamp = zeros(Nrows,1);
outDeltaAlpha = zeros(Nrows,1);
outDeltaNS = zeros(Nrows,1);
outOmegaDegH = zeros(Nrows,1);
outKTdot = zeros(Nrows,1);
outPass = false(Nrows,1);

row = 0;

for km = 1:Nm

    for ke = 1:numel(strainTransfer)

        eta = strainTransfer(ke);

        for kp = 1:numel(pairMismatchSweep)

            mismatch = pairMismatchSweep(kp);

            for kr = 1:numel(rampSweep_C_min)

                row = row+1;

                ramp_C_min = ...
                    rampSweep_C_min(kr);

                Tdot_C_s = ...
                    ramp_C_min/60;

                deltaAlphaEff = ...
                    mismatch*eta* ...
                    (alpha_structure(km)-alpha_fiber);

                deltaNS = ...
                    n_eff*(1-p_e)*deltaAlphaEff;

                omega_rad_s = ...
                    n_g*L/(4*D) * ...
                    deltaNS*Tdot_C_s;

                omega_deg_h = ...
                    omega_rad_s*180/pi*3600;

                outMaterial(row) = material(km);
                outTransferName(row) = transferName(ke);
                outEta(row) = eta;
                outMismatch(row) = mismatch;
                outRamp(row) = ramp_C_min;
                outDeltaAlpha(row) = deltaAlphaEff*1e6;
                outDeltaNS(row) = deltaNS*1e6;
                outOmegaDegH(row) = omega_deg_h;
                outKTdot(row) = omega_deg_h/ramp_C_min;
                outPass(row) = ...
                    abs(omega_deg_h) <= stress_budget_deg_h;
            end
        end
    end
end

stressSweep = table( ...
    outMaterial, ...
    outTransferName, ...
    outEta, ...
    100*outMismatch, ...
    outRamp, ...
    outDeltaAlpha, ...
    outDeltaNS, ...
    outOmegaDegH, ...
    outKTdot, ...
    outPass, ...
    'VariableNames', ...
    { ...
    'Former_material', ...
    'Stress_transfer_scenario', ...
