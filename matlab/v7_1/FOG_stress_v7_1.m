    'Paired_stress_mismatch_percent', ...
    'Temperature_ramp_C_per_min', ...
    'Delta_alpha_effective_ppm_K', ...
    'Delta_nS_ppm_K', ...
    'Mohr_Tdot_rate_error_deg_h', ...
    'K_Tdot_deg_h_per_C_min', ...
    'Pass_stress_budget' ...
    });

