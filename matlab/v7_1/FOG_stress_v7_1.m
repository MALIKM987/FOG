    23.6e-6; ...
    1.30e-6; ...
    9.0e-6; ...
    110e-6; ...
    0.55e-6 ...
    ];

Nm = numel(material);

CTE_mismatch = ...
    abs(alpha_structure-alpha_fiber);

%% ============================================================
% SCENARIUSZE TRANSFERU NAPREZEN
